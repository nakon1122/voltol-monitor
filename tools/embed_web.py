# Gzip assets/web/index.html into include/web_page.h (served by src/web.cpp).
import gzip
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
raw = (ROOT / 'assets/web/index.html').read_bytes()
gz = gzip.compress(raw, 9, mtime=0)
lines = ['// Generated by tools/embed_web.py from assets/web/index.html. Do not edit.',
         f'static const uint8_t WEB_PAGE_GZ[{len(gz)}] PROGMEM = {{']
for i in range(0, len(gz), 32):
    lines.append(','.join(str(b) for b in gz[i:i + 32]) + ',')
lines.append('};')
(ROOT / 'include/web_page.h').write_text('\n'.join(lines) + '\n')
print(f'web page: {len(raw)} -> {len(gz)} bytes gz')
