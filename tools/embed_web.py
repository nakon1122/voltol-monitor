# 1. Copy the board's Thai table (src/i18n.cpp) into assets/web/index.html
#    (between /*I18N*/ and /*I18N-END*/), so screen and web page use the same words.
# 2. Gzip assets/web/index.html into include/web_page.h (served by src/web.cpp).
import gzip, json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
src = (ROOT / 'src/i18n.cpp').read_text(encoding='utf-8')
pairs = re.findall(r'\{"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\}', src)
table = {json.loads(f'"{a}"'): json.loads(f'"{b}"') for a, b in pairs}
page = ROOT / 'assets/web/index.html'
html = page.read_text(encoding='utf-8')
html = re.sub(r'/\*I18N\*/.*?/\*I18N-END\*/',
              lambda m: '/*I18N*/const I18N=' + json.dumps(table, ensure_ascii=False, separators=(',', ':')) + ';/*I18N-END*/',
              html, count=1, flags=re.S)
page.write_text(html, encoding='utf-8')
raw = html.encode('utf-8')
gz = gzip.compress(raw, 9, mtime=0)
lines = ['// Generated by tools/embed_web.py from assets/web/index.html. Do not edit.',
         f'static const uint8_t WEB_PAGE_GZ[{len(gz)}] PROGMEM = {{']
for i in range(0, len(gz), 32):
    lines.append(','.join(str(b) for b in gz[i:i + 32]) + ',')
lines.append('};')
(ROOT / 'include/web_page.h').write_text('\n'.join(lines) + '\n')
print(f'web page: {len(raw)} -> {len(gz)} bytes gz, {len(table)} Thai entries')
